fn temp_root(label: &str) -> PathBuf {
    std::env::temp_dir().join(format!("saya-nested-{label}-{}", std::process::id()))
}

fn temp_run(label: &str, id: &str) -> RunDir {
    let root = temp_root(label);
    let _ = fs::remove_dir_all(&root);
    RunDir::create(&root, &RunId::parse(id).unwrap()).unwrap()
}

