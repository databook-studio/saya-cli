#[test]
fn the_composed_argv_is_the_bench_question_shape() {
    let run = temp_run("compose-argv", "argv-1");
    let state = nested_saya::prepare(
        &run,
        &[endpoint("orchestrator", None)],
        &Default::default(),
        &[],
    )
    .unwrap();
    let mut actual = state.ask_argv("orchestrator", "how many orders?");
    let mut expected = vec![
        "ask".to_owned(),
        "--config".into(),
        run.state()
            .join("config")
            .join("config.toml")
            .display()
            .to_string(),
        "--connections".into(),
        run.state()
            .join("config")
            .join("connections.toml")
            .display()
            .to_string(),
        "--profile".into(),
        "orchestrator".into(),
        "--non-interactive".into(),
        "--trust-project-config".into(),
        "--approval-mode".into(),
        "read-only".into(),
        "--format".into(),
        "ndjson".into(),
        "how many orders?".into(),
    ];
    // The generated argv uses forward slashes even on Windows, while
    // PathBuf::display uses native backslashes there. Compare the paths
    // portably without weakening the pinned flag order.
    for index in [2, 4] {
        actual[index] = actual[index].replace('\\', "/");
        expected[index] = expected[index].replace('\\', "/");
    }
    assert_eq!(
        actual, expected,
        "the invocation shape is bench.py:321-332, flag order pinned, plus the trust flag"
    );
    let _ = fs::remove_dir_all(run.root());
}

#[test]
fn prepare_generates_the_child_configs_and_pins_everything_inside_state() {
    let run = temp_run("compose-pins", "pins-1");
    let state = nested_saya::prepare(
        &run,
        &[endpoint("orchestrator", None)],
        &Default::default(),
        &[],
    )
    .unwrap();
    assert!(state.config_toml().exists(), "the generated config exists");
    assert!(
        state.connections_toml().exists(),
        "the generated connections exist"
    );
    assert_eq!(
        state.state_dir(),
        run.state(),
        "the pinned world is the run state"
    );
    for (name, path) in state.pinned_env() {
        assert!(
            path.starts_with(run.state()),
            "{name}={path:?} must resolve inside runs/<id>/state"
        );
    }
    let _ = fs::remove_dir_all(run.root());
}

#[test]
fn endpoint_credentials_mirror_the_generated_bindings() {
    let reference = SecretRef::Env {
        env: "SAYA_TEST_KEY_SOURCE".to_string(),
    };
    let endpoints = vec![
        endpoint("primary", Some(reference)),
        endpoint("orchestrator", None),
    ];
    let bindings = EndpointBindings::new([("orchestrator", "primary")]).unwrap();

    let credentials = nested_saya::endpoint_credentials(&endpoints, &bindings).unwrap();
    assert_eq!(credentials.len(), 1, "only the bound endpoint has a key");
    assert_eq!(credentials[0].env_var(), "SAYA_RUN_EP_ORCHESTRATOR");
    assert_eq!(credentials[0].name(), "primary");

    // Two roles uppercasing to one env name are refused, mirroring
    // `write_run_configs`' own duplicate-binding refusal.
    let colliding =
        EndpointBindings::new([("review-1", "primary"), ("review_1", "primary")]).unwrap();
    assert!(nested_saya::endpoint_credentials(&endpoints, &colliding).is_err());
}

