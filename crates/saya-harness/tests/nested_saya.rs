fn temp_root(label: &str) -> PathBuf {
    std::env::temp_dir().join(format!("saya-nested-{label}-{}", std::process::id()))
}

fn temp_run(label: &str, id: &str) -> RunDir {
    let root = temp_root(label);
    let _ = fs::remove_dir_all(&root);
    RunDir::create(&root, &RunId::parse(id).unwrap()).unwrap()
}

fn endpoint(name: &str, api_key: Option<SecretRef>) -> EndpointSpec {
    EndpointSpec {
        name: name.to_string(),
        provider: "anthropic".to_string(),
        model: "claude-test-model".to_string(),
        base_url: Some("https://api.test".to_string()),
        api_key,
    }
}

fn corpus(name: &str, path: &str) -> CorpusProfile {
    CorpusProfile {
        name: name.to_string(),
        path: path.to_string(),
    }
}

