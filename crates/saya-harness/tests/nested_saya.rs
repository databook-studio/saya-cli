//! The M5-5 nested-saya battery: what a re-entering `saya` child can
//! actually see and open, proven through a real spawn — the escape battery
//! (tests/runner.rs) is the precedent for how a constraint is proven here.
//!
//! 1. **The re-entry test.** With the environment pinned, the child's world
//!    holds no production profile: the generated `connections.toml` it opens
//!    lacks it, the child's own user-layer resolution lands inside run state
//!    where nothing exists, and the planted real user config is denied by
//!    the sandbox outright. Asserted on what the child could actually open
//!    — its own report — never on a flag.
//! 2. **The generated-config sentinel scan, through a real spawn.** A
//!    planted resolved value reaches the child's environment exactly once
//!    (the declared endpoint var, reported hashed so no captured lane ever
//!    carries the value), appears in no generated byte under the run dir,
//!    and rides no other channel — not the argv it received, not another
//!    environment entry. A resolved secret on disk fails this test forever.
//! 3. **The cwd pin.** The child's cwd is the run workspace; a
//!    `connections.toml` planted in the *parent's* cwd is not discovered by
//!    the child's own discovery scan — and the sandbox denies reading it by
//!    path. Both closures, not either.
//! 4. **The environment pins.** The child's `SAYA_CONFIG_HOME`,
//!    `SAYA_STATE_DB`, and `SAYA_SESSION_DIR` all resolve inside
//!    `runs/<id>/state/`.
//!
//! Spawn-dependent, so like the escape battery this file needs the startup
//! probe to prove the sandbox: macOS today (the M5-3 decision this slice
//! consumes); elsewhere it compiles to an empty main. The pure composition
//! (argv shape, pin locations, credential mapping) is tested
//! unconditionally, above the battery.

