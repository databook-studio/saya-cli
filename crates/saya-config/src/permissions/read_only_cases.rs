/// The shapes that keep the question. One row per reason, so a widening of the
/// set names the shape it gives up.
pub(super) const ASKING: &[&str] = &[
    // Output redirection to a file, in every spelling.
    "ls > out.txt",
    "ls >> out.txt",
    "ls &> out.txt",
    "ls 2> err.txt",
    "ls >| out.txt",
    "ls > out.txt 2>&1",
    // Command and process substitution, heredocs.
    "echo $(rm -rf x)",
    "echo `rm -rf x`",
    "cat <(ls)",
    "ls <<EOF",
    // A pipeline or chain with one part outside the set.
    "cat x | sh",
    "cat x | bash",
    "cat x | tee out.txt",
    "cat x | xargs rm",
    "cat x | sh -c 'ls'",
    "ls && rm -rf x",
    "ls; rm -rf x",
    "ls || rm -rf x",
    "ls &",
    "grep -rn foo src && rm x",
    // A launcher, an interpreter, or a program that is not vetted at all.
    "sudo ls",
    "doas ls",
    "sh -c 'ls'",
    "eval ls",
    "timeout 5 ls",
    "nice ls",
    "nohup ls",
    "stdbuf -oL ls",
    "xargs ls",
    "env ls",
    "exec ls",
    "python -c 'print(1)'",
    "python3 x.py",
    "awk '{print}' README.md",
    "npm install",
    "make check",
    "rm -rf build",
    "curl https://example",
    // An environment assignment can change what the program reads or which
    // program runs.
    "PATH=/tmp ls",
    "LD_PRELOAD=x ls",
    "GIT_PAGER=less git log",
    // A flag that writes, follows, or runs a program.
    "tail -f run.log",
    "tail -F run.log",
    "sort -o out.txt Cargo.toml",
    "tree -o out.txt",
    "uniq a.txt b.txt",
    "file -C",
    "file -bC",
    "rg --pre ./pre.sh foo",
    // `find` actions that run a program, delete, or write a file.
    "find . -exec rm {} \\;",
    "find . -execdir ls {} +",
    "find . -ok rm {} \\;",
    "find . -delete",
    "find . -fprint out.txt",
    // `git` spellings that run a program, page, or change the repository.
    "git push",
    "git checkout main",
    "git remote",
    "git remote add origin https://example",
    "git branch -D feat",
    "git branch new-branch",
    "git -c core.pager=x log",
    "git --exec-path=/tmp log",
    "git --paginate log",
    "git log --ext-diff",
    "git diff --output=o.txt",
    "git log --output=o.txt",
    "git status && git push",
    // A path that leaves the workspace, or names a file the workspace tools
    // refuse: the read tool's own private-path rule, so the set never reads
    // what the tools will not.
    "cat ~/.ssh/id_rsa",
    "cat /etc/passwd",
    "head ../x/.env",
    "cat .env",
    "cat src/../../x",
    "diff a /etc/hosts",
    "grep -f /etc/x y",
    // A shell expansion: what the command reads is not what it says.
    "echo $HOME",
    "echo ${KEY}",
    "ls ~",
    // An unquoted glob expands to names the command never wrote, hidden and
    // private ones included.
    "cat *",
    "cat *.env",
    "grep -n foo *",
    // A recursive content read reaches the hidden files a path rule cannot
    // name.
    "grep -r KEY .",
    "grep -R x src",
    "rg --hidden KEY",
    "rg -uu KEY",
    "rg -z x",
];
